""" Shared limits and exit codes without importing the PDF renderer """

MAX_MARKDOWN_CHARS = 200_000
MAX_REPORT_TITLE_CHARS = 200
MAX_PDF_BYTES = 10 * 1024 * 1024
MAX_REPORT_IMAGES = 16
MAX_REPORT_IMAGE_PATH_CHARS = 2048
MAX_REPORT_IMAGE_BYTES = 16 * 1024 * 1024
MAX_REPORT_IMAGE_PIXELS = 40_000_000

# An escaped non-BMP character takes twelve bytes in ASCII JSON
MAX_REPORT_JOB_BYTES = 12 * (MAX_MARKDOWN_CHARS + MAX_REPORT_TITLE_CHARS) + 128
# Base64 payloads and escaped image references also travel through stdin
MAX_REPORT_JOB_BYTES += 4 * ((MAX_REPORT_IMAGE_BYTES + 2) // 3)
MAX_REPORT_JOB_BYTES += MAX_REPORT_IMAGES * (12 * MAX_REPORT_IMAGE_PATH_CHARS + 64)

REPORT_MEMORY_BYTES = 2 * 1024 * 1024 * 1024
REPORT_CPU_SECONDS = 30
REPORT_TOTAL_TIMEOUT = 60.0
REPORT_POLL_INTERVAL = 0.1

REPORT_EXIT_INVALID = 2
REPORT_EXIT_BLOCKED = 3
REPORT_EXIT_MEMORY = 4
REPORT_EXIT_FAILED = 5
REPORT_EXIT_LIMITS = 6
